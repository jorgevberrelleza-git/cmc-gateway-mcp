import assert from 'node:assert/strict';
import {createGroqResearchCanary,validateResearchObservation} from '../src/learning/groq-research-canary.mjs';
const observation={asset:'BTC',observed_at:'2026-11-03T18:00:00Z',facts:['spot trend unverified']};
assert.equal(validateResearchObservation(observation).asset,'BTC');
assert.throws(()=>validateResearchObservation({...observation,asset:'DOGE'}),/unsupported_asset/);
let calls=0;
const fakeFetch=async(_url,args)=>{
  calls++;
  assert.equal(args.method,'POST');
  assert.equal(args.signal.aborted,false);
  const request=JSON.parse(args.body);
  assert.equal(request.model,'openai/gpt-oss-20b');
  assert.equal(request.messages[1].role,'user');
  return {ok:true,json:async()=>({choices:[{message:{content:JSON.stringify({summary:'Insufficient evidence',risks:['Data gap'],gaps:['Verify venue'],confidence:'low'})}}]})};
};
const disabled=await createGroqResearchCanary({enabled:false,apiKey:'fake',fetchImpl:fakeFetch}).analyze(observation);
assert.equal(disabled.skipped,true);
assert.equal(calls,0);
const missing=await createGroqResearchCanary({enabled:true,apiKey:'',fetchImpl:fakeFetch}).analyze(observation);
assert.equal(missing.reason,'GROQ_API_KEY_missing');
assert.equal(calls,0);
const result=await createGroqResearchCanary({enabled:true,apiKey:'fake',fetchImpl:fakeFetch}).analyze(observation);
assert.equal(result.ok,true);
assert.equal(result.analysis.confidence,'low');
assert.equal(result.execution_enabled,false);
assert.equal(result.authorizes_position_change,false);
assert.equal(calls,1);
console.log(JSON.stringify({ok:true,tests:8,network_calls:0,execution_enabled:false}));
